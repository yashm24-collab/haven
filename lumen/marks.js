// Generates the dock's brand marks: crisp vectors from Simple Icons (CC0), coloured for a dark plate, plus each
// app's brand colour for the focus glow. JioHotstar is not in Simple Icons, so its white logo is keyed out of the
// TV's own icon. That copy is the app's artwork, not ours to publish: launcher/marks/hotstar.png is gitignored and
// made only when sync-apps.py has fetched the icon; without it the dock falls back to the TV's icon (app.js).
// Output: launcher/marks/*, launcher/marks.js. Run: node lumen/marks.js
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const si = require('simple-icons');
const OUT = path.join(__dirname, '../launcher/marks');
fs.mkdirSync(OUT, { recursive: true });

// appId: [simple-icons export, fill on the dark plate, focus glow colour, display name, tight viewBox]
// Tight viewBoxes were measured with getBBox in a browser (Node can't): the icons sit in a 24x24 square, and a
// wide wordmark like Prime Video's would otherwise shrink to a third of the tile's height.
const MARKS = {
  netflix: ['siNetflix', '#E50914', '#E50914', 'Netflix', '5.4 0 13.2 24'],
  amazon: ['siPrimevideo', '#00A8E1', '#00A8E1', 'Prime Video', '0 8.32 24 7.37'],
  'youtube.leanback.v4': ['siYoutube', '#FF0000', '#FF0000', 'YouTube', '0 3.55 24 16.91'],
  'spotify-beehive': ['siSpotify', '#1ED760', '#1ED760', 'Spotify', '0 0 24 24'],
  'com.apple.appletv': ['siAppletv', '#F3ECE1', '#E8DCC8', 'Apple TV', '0 6.12 24 11.75'],
};
const data = {};
for (const [id, [key, fill, glow, name, box]] of Object.entries(MARKS)) {
  const icon = si[key];
  if (!icon) throw new Error('missing simple icon ' + key);
  // YouTube's mark is a red button with a cut-out triangle: put a white play symbol behind it.
  const under = key === 'siYoutube' ? '<polygon points="9.4,8.3 9.4,15.7 16,12" fill="#fff"/>' : '';
  fs.writeFileSync(path.join(OUT, id + '.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box}">${under}<path fill="${fill}" d="${icon.path}"/></svg>`);
  data[id] = { src: 'marks/' + id + '.svg', glow, name };
}

// JioHotstar: key the flat blue out of the 130px TV icon, trim, and upscale 3x for smoother edges.
const icon = path.join(__dirname, '../launcher/icons/hotstar.png');
if (fs.existsSync(icon)) execFileSync(require('ffmpeg-static'), ['-loglevel', 'error', '-y', '-i', icon,
  '-vf', 'format=rgba,colorkey=0x1492FF:0.3:0.12,crop=106:59:12:32,scale=318:177:flags=lanczos', path.join(OUT, 'hotstar.png')]);
data.hotstar = { src: 'marks/hotstar.png', glow: '#1F80E0', name: 'JioHotstar' };

fs.writeFileSync(path.join(__dirname, '../launcher/marks.js'),
  '// Generated by lumen/marks.js: dock brand marks and focus glow colours.\nwindow.MARKS = ' + JSON.stringify(data, null, 1) + ';\n');
console.log('marks:', Object.keys(data).join(', '), fs.existsSync(icon) ? '' : '(no TV icon for hotstar: its tile uses the TV icon)');
